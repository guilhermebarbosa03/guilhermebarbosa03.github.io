const ICONS = Object.fromEntries(
  Object.entries(ART).map(([name, rows]) => [name, artToPath(rows)]),
) as Record<IconName, string>;

interface PixelIconProps {
  name: IconName;
  /** Rendered size in px. Use multiples of 16 for crisp pixels. */
  size?: number;
  className?: string;
}

export function PixelIcon({ name, size = 16, className }: PixelIconProps) {
  return (
    <svg
      width={size}
      height={size}
      viewBox="0 0 16 16"
      fill="currentColor"
      shapeRendering="crispEdges"
      aria-hidden="true"
      focusable="false"
      className={className}
    >
      <path d={ICONS[name]} />
    </svg>
  );
}
