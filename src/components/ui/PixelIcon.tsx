/**
 * Turns 16 rows of ASCII art ("#" = filled pixel) into one SVG path made of rectangles.
 * Equal horizontal runs on consecutive rows are merged, which keeps the markup short.
 */
function artToPath(rows: readonly string[]): string {
  const rects: string[] = [];
  let open = new Map<string, number>(); // "x:width" -> row where that run started

  const flush = (key: string, startRow: number, endRow: number) => {
    const [x, width] = key.split(":").map(Number);
    rects.push(`M${x} ${startRow}h${width}v${endRow - startRow}h${-width}z`);
  };

  for (let y = 0; y <= rows.length; y++) {
    const current = new Map<string, number>();
    const row = rows[y] ?? "";
    for (let x = 0; x < row.length; ) {
      if (row[x] !== "#") {
        x++;
        continue;
      }
      let end = x;
      while (row[end] === "#") end++;
      const key = `${x}:${end - x}`;
      current.set(key, open.get(key) ?? y);
      x = end;
    }
    for (const [key, startRow] of open) {
      if (!current.has(key)) flush(key, startRow, y);
    }
    open = current;
  }

  return rects.join("");
}

